export function exerciseMovement(id){
  const definition=movements[id];
  if(!definition)return null;
  const [motion,cue,...links]=definition;
  return {motion,cue,links:links.map(([key,role,actions])=>({muscle:byId.get(key),role,actions:actions.split('|')})).filter(link=>link.muscle)};
}

export function relatedExercises(muscleId,catalog,purpose){
  return catalog.filter(exercise=>exerciseMovement(exercise.id)?.links.some(
    link=>link.muscle.id===muscleId&&(!purpose||link.actions.includes(purpose))
  ));
}
